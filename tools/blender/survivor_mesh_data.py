"""Writes mod/PacificTogether/Scripts/survivor_mesh.lua: the geometry of tools/blender/survivor_model.py without Blender.

Same bones (head/tail) and primitives (cone, sphere, box; box bevels are dropped, they are 4-40 mm) as survivor_model.py.
Output per bone: positions relative to the bone head in cm, already in Unreal component axes (x = bx, y = -by, z = bz;
character faces +Y, +X is its left), normals, 0-based triangles per material, and the bone direction. Run: python tools/blender/survivor_mesh_data.py
"""
import math, os, re

SRC = open(os.path.join(os.path.dirname(__file__), "survivor_model.py"), encoding="utf-8").read()
# bones and materials are read from the original so the two files cannot drift
ns = {}
exec(re.search(r"^bones = \[.*?^\]\n", SRC, re.S | re.M).group(0), ns)
exec(re.search(r"^for s, sd in \(\(1, \"l\"\), \(-1, \"r\"\)\):\n    bones \+= \[.*?^    \]\n", SRC, re.S | re.M).group(0), ns)
bones = ns["bones"]
MATS = eval(re.search(r"^MATS = (\[.*?\])\n", SRC, re.S | re.M).group(1).replace("\n", " "))
SUIT, BOOTS, GLOVES, SKIN, HAIR, GEAR = range(6)
head = {b[0]: b[1] for b in bones}
tail = {b[0]: b[2] for b in bones}

def sub(a, b): return (a[0]-b[0], a[1]-b[1], a[2]-b[2])
def add(a, b): return (a[0]+b[0], a[1]+b[1], a[2]+b[2])
def mul(a, k): return (a[0]*k, a[1]*k, a[2]*k)
def cross(a, b): return (a[1]*b[2]-a[2]*b[1], a[2]*b[0]-a[0]*b[2], a[0]*b[1]-a[1]*b[0])
def norm(a):
    l = math.sqrt(sum(x*x for x in a)) or 1.0
    return (a[0]/l, a[1]/l, a[2]/l)

parts = []  # (bone, mat, [(pos, normal)] per tri-vertex triple lists)

def emit(bone, mat, tris):
    parts.append((bone, mat, tris))

def basis(d):
    d = norm(d)
    a = (1, 0, 0) if abs(d[0]) < 0.9 else (0, 1, 0)
    u = norm(cross(d, a)); v = cross(d, u)
    return u, v, d

def cone(bone, p0, p1, r0, r1, mat, seg=10):
    u, v, d = basis(sub(p1, p0))
    ring = lambda p, r: [add(p, add(mul(u, r*math.cos(2*math.pi*i/seg)), mul(v, r*math.sin(2*math.pi*i/seg)))) for i in range(seg)]
    a, b = ring(p0, r0), ring(p1, r1)
    slope = (r0 - r1) / (math.dist(p0, p1) or 1)
    def rn(i):
        c, s = math.cos(2*math.pi*i/seg), math.sin(2*math.pi*i/seg)
        return norm(add(add(mul(u, c), mul(v, s)), mul(d, slope)))
    tris = []
    for i in range(seg):
        j = (i+1) % seg
        for q in ((a[i], a[j], b[j]), (a[i], b[j], b[i])):
            tris.append([(q[k], rn(i if q[k] in (a[i], b[i]) else j)) for k in range(3)])
    for ring_, p, n in ((a, p0, mul(d, -1)), (b, p1, d)):
        for i in range(seg):
            tri = (p, ring_[i], ring_[(i+1) % seg]) if n == d else (p, ring_[(i+1) % seg], ring_[i])
            tris.append([(x, n) for x in tri])
    emit(bone, mat, tris)

def sphere(bone, c, r, mat, us=10, vs=7):
    def pt(i, j):  # j = 0 north pole .. vs south pole
        th, ph = math.pi*j/vs, 2*math.pi*i/us
        return (math.sin(th)*math.cos(ph), math.sin(th)*math.sin(ph), math.cos(th))
    def vert(i, j):
        n = pt(i, j)
        return (add(c, (n[0]*r[0], n[1]*r[1], n[2]*r[2])), norm((n[0]/r[0], n[1]/r[1], n[2]/r[2])))
    tris = []
    for i in range(us):
        for j in range(vs):
            a, b, c2, d = vert(i, j), vert(i+1, j), vert(i+1, j+1), vert(i, j+1)
            if j > 0: tris.append([a, b, c2])
            if j < vs-1: tris.append([a, c2, d])
    emit(bone, mat, tris)

def box(bone, c, size, mat, bevel=0.0):
    h = [s/2 for s in size]
    tris = []
    for axis in range(3):
        for sg in (1, -1):
            n = [0, 0, 0]; n[axis] = sg; n = tuple(n)
            u, v = [(1, 2), (2, 0), (0, 1)][axis]
            def corner(a, b):
                p = [0, 0, 0]; p[axis] = sg*h[axis]; p[u] = a*h[u]; p[v] = b*h[v]
                return (add(c, tuple(p)), n)
            q = [corner(-1, -1), corner(1, -1), corner(1, 1), corner(-1, 1)]
            tris += [[q[0], q[1], q[2]], [q[0], q[2], q[3]]]
    emit(bone, mat, tris)

# the geometry calls of survivor_model.py, verbatim (between "# head" and "me = bpy.data.meshes.new")
body = SRC.split("# head\n", 1)[1].split("me = bpy.data.meshes.new", 1)[0]
exec("# head\n" + body, dict(globals(), Vector=lambda t: tuple(t)))

def ue(p): return (round(p[0]*100, 2), round(-p[1]*100, 2), round(p[2]*100, 2))
def uen(n): return (round(n[0], 3), round(-n[1], 3), round(n[2], 3))

out = ["-- generated by tools/blender/survivor_mesh_data.py from tools/blender/survivor_model.py: do not edit",
       "return {", "  colors = {" + ", ".join("{%g,%g,%g}" % m[1] for m in MATS) + "},", "  bones = {"]
per = {}
for bone, mat, tris in parts:
    per.setdefault(bone, {}).setdefault(mat, []).extend(tris)
vcount = 0
for name, h, t, parent in bones:
    if name not in per: continue
    d = ue(sub(t, h)); dn = norm(d)
    out.append('    %s = { dir = {%.4f,%.4f,%.4f}, len = %.2f, sections = {' % (name, *dn, math.dist(t, h) * 100))
    for mat, tris in sorted(per[name].items()):
        V, N, T = [], [], []
        for tri in tris:
            for p, n in tri:
                q, nn = ue(sub(p, h)), uen(n)
                T.append(len(V)//3)
                V += q; N += nn
        vcount += len(T)
        out.append("      { mat = %d, v = {%s}, n = {%s}, t = {%s} }," % (mat+1, ",".join("%g" % x for x in V), ",".join("%g" % x for x in N), ",".join(str(x) for x in T)))
    out.append("    } },")
out += ["  },", "}"]
path = os.path.join(os.path.dirname(__file__), "..", "..", "mod", "PacificTogether", "Scripts", "survivor_mesh.lua")
open(path, "w", encoding="utf-8").write("\n".join(out) + "\n")
print("bones with parts", len(per), "tri-vertices", vcount, "bytes", os.path.getsize(path))
